"""Supporting check (docs/RESEARCH.md §7, D-31): BKT against a plain percentage of correct answers on SYNTHETIC students.

Each synthetic student has a hidden "knows the skill" state that can flip to known after every answer, and answers
questions with a slip or guess chance. We know the truth, so we can ask: which tracker predicts the next answer better
(AUC), and which one declares mastery sooner and with fewer false positives?

Everything here is generated by code with a fixed seed. The generator is itself a BKT-shaped process, so the
"matched" scenario favours BKT by construction; the other scenarios give the BKT in the app wrong parameters on
purpose. This says something about the engineering choice, not about real learners.

    python analysis/sim_bkt.py [--out analysis/out/synthetic]
"""

import argparse
import csv
from pathlib import Path

import numpy as np
from scipy.stats import rankdata

from common import Report, bkt_selfcheck, bkt_update

SEED = 20261118
STUDENTS = 3000
QUESTIONS = 12  # answers per student on one skill
# what the app assumes (config defaults, SPEC D-14); the true process differs per scenario
APP = {"p_init": 0.20, "learn": 0.15, "slip": 0.10, "guess": 0.25}
THRESHOLD = 0.80
SCENARIOS = {
    "matched": {"p_init": 0.20, "learn": 0.15, "slip": 0.10, "guess": 0.25},
    "mismatched": {"p_init": 0.35, "learn": 0.08, "slip": 0.20, "guess": 0.25},
    "lucky_guessing": {"p_init": 0.20, "learn": 0.15, "slip": 0.10, "guess": 0.40},
}
RULES = {  # name -> (kind, window, needed): "pct" = running share >= 80 % after at least `window` answers
    "BKT >= 0.80": ("bkt", 1, 0),
    "share correct >= 80 % (all answers, min 3)": ("pct", 3, 0),
    "last 3 answers all correct": ("window", 3, 3),
    "4 of the last 5 correct": ("window", 5, 4),
}


def simulate(true: dict, rng: np.random.Generator):
    """Returns correct (N, L) and known (N, L+1): known[:, t] is the hidden state that produces answer t+1."""
    n = STUDENTS
    known = np.zeros((n, QUESTIONS + 1), dtype=bool)
    known[:, 0] = rng.random(n) < true["p_init"]
    correct = np.zeros((n, QUESTIONS), dtype=bool)
    for t in range(QUESTIONS):
        p_correct = np.where(known[:, t], 1 - true["slip"], true["guess"])
        correct[:, t] = rng.random(n) < p_correct
        known[:, t + 1] = known[:, t] | (rng.random(n) < true["learn"])
    return correct, known


def trackers(correct: np.ndarray):
    """P(known) after each answer from the app's BKT, and the running share correct."""
    n, length = correct.shape
    p = np.full(n, APP["p_init"])
    bkt = np.zeros((n, length))
    for t in range(length):
        p = np.array([bkt_update(pi, c, APP["guess"], APP["slip"], APP["learn"]) for pi, c in zip(p, correct[:, t])])
        bkt[:, t] = p
    pct = np.cumsum(correct, axis=1) / np.arange(1, length + 1)
    return bkt, pct


def auc(scores: np.ndarray, labels: np.ndarray) -> float:
    ranks = rankdata(scores)
    n1 = labels.sum()
    n0 = len(labels) - n1
    return float((ranks[labels].sum() - n1 * (n1 + 1) / 2) / (n1 * n0))


def next_answer_auc(bkt, pct, correct, rng, n_boot=500):
    """AUC of predicting answer t+1 from answers 1..t (t = 1..L-1), pooled; bootstrap over students."""
    # BKT's p is the state AFTER the learning step, so P(correct next) = p (1 - slip) + (1 - p) guess
    pred_bkt = bkt[:, :-1] * (1 - APP["slip"]) + (1 - bkt[:, :-1]) * APP["guess"]
    pred_pct = pct[:, :-1]
    target = correct[:, 1:]

    def pooled(idx):
        y = target[idx].ravel()
        return auc(pred_bkt[idx].ravel(), y), auc(pred_pct[idx].ravel(), y)

    everyone = np.arange(len(correct))
    a_bkt, a_pct = pooled(everyone)
    diffs, lo_b, lo_p = [], [], []
    for _ in range(n_boot):
        b, p = pooled(rng.integers(0, len(correct), len(correct)))
        diffs.append(b - p)
        lo_b.append(b)
        lo_p.append(p)
    q = lambda v: (float(np.quantile(v, 0.025)), float(np.quantile(v, 0.975)))
    return {"bkt": a_bkt, "bkt_ci": q(lo_b), "pct": a_pct, "pct_ci": q(lo_p), "diff": a_bkt - a_pct, "diff_ci": q(diffs)}


def detection(rule, bkt, pct, known, correct):
    """When does a rule declare mastery, and was the student really in the known state at that moment?"""
    kind, window, needed = RULES[rule]
    if kind == "window":
        csum = np.cumsum(correct, axis=1)
        recent = csum - np.concatenate([np.zeros((len(csum), window), dtype=int), csum[:, :-window]], axis=1)
        passed = recent >= needed
        passed[:, : window - 1] = False
    else:
        passed = (bkt if kind == "bkt" else pct) >= (THRESHOLD - 1e-9)
        passed[:, : window - 1] = False
    n, length = passed.shape
    declared = passed.any(axis=1)
    at = np.where(declared, passed.argmax(axis=1), -1)  # 0-based index of the answer after which it fires
    state_after = known[:, 1:]  # state that produces the NEXT answer, i.e. after answer t
    rows = np.arange(n)
    really = np.where(declared, state_after[rows, np.maximum(at, 0)], False)
    # first answer after which the student is truly in the known state (state_after is monotone in t)
    ever = state_after.any(axis=1)
    learned_at = np.where(ever, state_after.argmax(axis=1), -1)
    true_pos = declared & really
    delay = (at - learned_at)[true_pos]
    return {
        "declared_share": float(declared.mean()),
        "false_positive_share": float(((declared & ~really).sum()) / max(declared.sum(), 1)),
        "median_delay_answers": float(np.median(delay)) if len(delay) else float("nan"),
        "missed_share": float(((ever & ~declared).sum()) / max(ever.sum(), 1)),
    }


def figure(out: Path, auc_rows, det_rows):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    blue, orange = "#0072B2", "#D55E00"
    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    names = list(SCENARIOS)
    x = np.arange(len(names))
    ax = axes[0]
    for k, (key, label, colour) in enumerate((("bkt", "BKT", blue), ("pct", "share correct", orange))):
        vals = [r[key] for r in auc_rows]
        err = [[r[key] - r[key + "_ci"][0] for r in auc_rows], [r[key + "_ci"][1] - r[key] for r in auc_rows]]
        ax.bar(x + (k - 0.5) * 0.35, vals, 0.35, yerr=err, color=colour, label=label, capsize=3)
    ax.set_ylim(0.5, 0.8)
    ax.set_xticks(x, names)
    ax.set_ylabel("AUC, next answer")
    ax.set_title("Predicting the next answer")
    ax.legend()
    rules = list(RULES)
    colours = [blue, orange, "#999999", "#009E73"]
    for ax, key, title, ylab in ((axes[1], "false_positive_share", "Declared mastery without knowing", "share of declarations"),
                                 (axes[2], "median_delay_answers", "Delay after the student truly learned", "median answers")):
        for k, rule in enumerate(rules):
            vals = [next(r[key] for r in det_rows if r["scenario"] == s and r["rule"] == rule) for s in names]
            ax.bar(x + (k - 1.5) * 0.2, vals, 0.2, color=colours[k], label=rule)
        ax.set_xticks(x, names)
        ax.set_ylabel(ylab)
        ax.set_title(title)
    handles, labels = axes[1].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=len(rules), fontsize=8, frameon=False)
    fig.suptitle(f"BKT vs percentage, {STUDENTS} synthetic students per scenario   [SOURCE: synthetic]", fontsize=10)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(out / "fig_bkt_vs_percentage.png", dpi=140)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=Path(__file__).parent / "out" / "synthetic")
    args = ap.parse_args()
    bkt_selfcheck()
    args.out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)
    rep = Report("Supporting check: BKT vs percentage of correct answers", "synthetic",
                 f"Seed {SEED}; {STUDENTS} students per scenario, {QUESTIONS} answers each on one skill. "
                 "The app's BKT always uses its config defaults "
                 f"(p_init {APP['p_init']}, learn {APP['learn']}, slip {APP['slip']}, guess {APP['guess']}); "
                 f"mastery threshold {THRESHOLD}. The BKT implementation was first checked against the OQ-11 numbers of the SPEC.")
    auc_rows, det_rows = [], []
    for name, true in SCENARIOS.items():
        correct, known = simulate(true, rng)
        bkt, pct = trackers(correct)
        a = next_answer_auc(bkt, pct, correct, rng)
        auc_rows.append({"scenario": name, **a})
        for rule in RULES:
            det_rows.append({"scenario": name, "rule": rule, **detection(rule, bkt, pct, known, correct)})
    rep.add("## True process per scenario", "")
    rep.table(["Scenario", "p_init", "learn", "slip", "guess"],
              [[n, *[t[k] for k in ("p_init", "learn", "slip", "guess")]] for n, t in SCENARIOS.items()])
    rep.add("## Predicting the next answer (AUC, pooled over answers 2..12)", "")
    rep.table(["Scenario", "BKT AUC [95 % CI]", "Share-correct AUC [95 % CI]", "Difference BKT − share [95 % CI]"],
              [[r["scenario"], f"{r['bkt']:.3f} [{r['bkt_ci'][0]:.3f}, {r['bkt_ci'][1]:.3f}]",
                f"{r['pct']:.3f} [{r['pct_ci'][0]:.3f}, {r['pct_ci'][1]:.3f}]",
                f"{r['diff']:+.3f} [{r['diff_ci'][0]:+.3f}, {r['diff_ci'][1]:+.3f}]"] for r in auc_rows])
    rep.add("Bootstrap over students (500 resamples). BKT and the share are both monotone in the number of correct "
            "answers, so their rankings can differ only through answer order and the prior; a small difference is expected.", "")
    rep.add("## Declaring mastery", "",
            "False positive = the rule fires while the student is, in truth, still in the unknown state. Delay = answers "
            "between the student truly learning and the rule firing (only for correct declarations). Missed = truly "
            f"learned within {QUESTIONS} answers but never declared.", "")
    rep.table(["Scenario", "Rule", "Declared", "False positives", "Median delay (answers)", "Missed"],
              [[r["scenario"], r["rule"], f"{100 * r['declared_share']:.1f} %", f"{100 * r['false_positive_share']:.1f} %",
                f"{r['median_delay_answers']:.1f}", f"{100 * r['missed_share']:.1f} %"] for r in det_rows])
    rep.add("## How to read this", "",
            "- The generator is a BKT process; \"matched\" is the best case for BKT and \"mismatched\"/\"lucky_guessing\" "
            "test it with wrong parameters. A percentage rule needs no parameters, which is its advantage in real life and "
            "is not captured here. The cumulative share is a weak baseline (an early mistake is never forgotten); the "
            "window rules are the fairer simple alternatives.",
            "- Real learners forget, vary by question and are not a two-state machine. Nothing here is evidence about "
            "real learners; it only compares the two trackers on data whose truth we know.", "")
    rep.save(args.out / "bkt_results.md")
    with (args.out / "bkt_detection.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(det_rows[0]))
        w.writeheader()
        w.writerows(det_rows)
    figure(args.out, auc_rows, det_rows)
    print(rep.text())


if __name__ == "__main__":
    main()
