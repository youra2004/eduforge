"""Helpers shared by the analysis scripts: source labels, a markdown report, Wilson intervals, the BKT update."""

import math
from pathlib import Path

SOURCES = ("real", "synthetic")


class Report:
    """Collects markdown lines, prints them and writes them to a file. Every report opens with its source label."""

    def __init__(self, title: str, source: str, note: str = ""):
        assert source in SOURCES
        self.source = source
        self.lines: list[str] = []
        banner = (
            "SOURCE: real (de-identified export of the study)"
            if source == "real"
            else "SOURCE: synthetic (generated by code with a fixed seed; not a research result)"
        )
        self.add(f"# {title}", "", f"**{banner}**")
        if note:
            self.add("", note)
        self.add("")

    def add(self, *lines: str) -> None:
        self.lines.extend(lines)

    def table(self, header: list[str], rows: list[list]) -> None:
        self.add("| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|")
        for r in rows:
            self.add("| " + " | ".join(str(c) for c in r) + " |")
        self.add("")

    def text(self) -> str:
        # the label closes the report as well, so a pasted excerpt cannot lose it
        return "\n".join(self.lines + ["", f"_source: {self.source}_", ""])

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.text())


def wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    """95 % Wilson score interval for a share k / n (well behaved for small n and for 0 or n successes)."""
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, centre - half), min(1.0, centre + half))


def pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.1f} %"


def bkt_update(p: float, correct: bool, guess: float, slip: float, learn: float) -> float:
    """SPEC F5-R2; the same formula as packages/core/src/learning/bkt.ts."""
    known = p * (1 - slip) if correct else p * slip
    unknown = (1 - p) * guess if correct else (1 - p) * (1 - guess)
    posterior = known / (known + unknown)
    return posterior + (1 - posterior) * learn


def bkt_selfcheck() -> None:
    """The OQ-11 numbers of the SPEC (also asserted by learning.test.ts on the TypeScript side)."""
    def run(seq):
        p = 0.20
        for c in seq:
            p = bkt_update(p, c, guess=0.25, slip=0.10, learn=0.15)
        return p

    assert abs(run([True, True, False]) - 0.51) < 0.005
    assert abs(run([True, True, True, False]) - 0.79) < 0.005
    assert abs(run([True, False, True, True]) - 0.88) < 0.005
    assert abs(run([True, True]) - 0.84) < 0.005  # M05: two correct answers in a row
